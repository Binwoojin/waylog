-- 근거 문서: docs/02-design/features/mypage-bookmarks.design.md §3.1, §3.3
-- 엔티티 근거: UserEntity.java(WITHDRAWN_AT 컬럼)
--
-- 적용 전 반드시 백업을 먼저 받으세요. 이미 실행한 환경에서 재실행하지 않도록 주의하세요.

-- ============================================================
-- 1. 회원(users) — 회원 탈퇴(영구적 로그인 차단, 설계 §3.1, §3.3)
--
-- 기존 정지(SUSPENDED_UNTIL 등, 2026-09-30-admin-dashboard.sql)와 다르게 "현재 시각과 비교"하는
-- 계산이 필요 없다(UserEntity.isWithdrawn()은 null 여부만 본다). 행을 삭제하지 않고 이 컬럼만
-- 채우는 소프트 삭제다 — feed_post.user_id가 nullable=false FK라 하드 삭제 시 FK 위반 또는
-- 연쇄 삭제가 강제되기 때문이다(설계 §3.3).
-- ============================================================
ALTER TABLE users
    ADD COLUMN WITHDRAWN_AT DATETIME NULL;

-- ============================================================
-- 참고: INTRODUCE 컬럼은 이번 기능에서 신규로 추가하지 않습니다.
-- UserEntity.java에 이미 @Column(name = "INTRODUCE", length = 200)으로 매핑되어 있고
-- 조사 결과 기존 users 테이블에 이미 존재하는 컬럼입니다(이번 기능 이전에는 어디서도
-- 읽거나 쓰이지 않던 죽은 컬럼이었을 뿐, 컬럼 자체는 이미 있었습니다). 따라서 이 마이그레이션은
-- WITHDRAWN_AT 추가 한 건만 다룹니다.
-- ============================================================

