-- 이 프로젝트에는 마이그레이션 도구(Flyway 등)가 없고 jpa.hibernate.ddl-auto: none이므로,
-- 배포 전에 이 스크립트를 직접 검토한 뒤 대상 DB에 수동으로 실행해야 합니다.
